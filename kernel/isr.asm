; =============================================================================
;  isr.asm — низкоуровневые обработчики прерываний (Interrupt Service Routines)
; =============================================================================
;  Когда происходит прерывание, процессор:
;    1. Сохраняет в стек EFLAGS, CS, EIP (куда потом вернуться).
;    2. Для некоторых исключений — ещё и "код ошибки".
;    3. Находит в таблице IDT адрес обработчика и прыгает туда.
;
;  Обработчик обязан сохранить ВСЕ регистры (прерванная программа ничего
;  не знает о прерывании и ожидает, что регистры не изменятся), сделать
;  работу и вернуться командой IRET (она снимает со стека EIP, CS, EFLAGS).
;
;  Писать 48 почти одинаковых обработчиков на C неудобно, да и сохранить
;  все регистры из C нельзя. Поэтому здесь маленькие "заглушки" (stubs):
;  каждая кладёт в стек номер прерывания и прыгает в общий код isr_common,
;  который сохраняет регистры и вызывает C-функцию interrupt_handler().
;
;  Подробно: docs/05-preryvaniya.md
; =============================================================================
[bits 32]

extern interrupt_handler        ; C-функция в interrupts.c

; Заглушка для исключения БЕЗ кода ошибки: кладём фиктивный 0,
; чтобы структура в стеке всегда была одинаковой.
%macro ISR_NO_ERROR 1
global isr%1
isr%1:
    push dword 0                ; фиктивный код ошибки
    push dword %1               ; номер прерывания
    jmp  isr_common
%endmacro

; Заглушка для исключения, для которого процессор САМ кладёт код ошибки
%macro ISR_WITH_ERROR 1
global isr%1
isr%1:
    push dword %1               ; номер прерывания
    jmp  isr_common
%endmacro

; Заглушка для аппаратного прерывания (IRQ). IRQ 0..15 после перенастройки
; контроллера прерываний приходят как векторы 32..47.
%macro IRQ 1
global irq%1
irq%1:
    push dword 0
    push dword (32 + %1)
    jmp  isr_common
%endmacro

; ---- Исключения процессора (векторы 0..31) ----
ISR_NO_ERROR   0    ; Деление на ноль
ISR_NO_ERROR   1    ; Отладка
ISR_NO_ERROR   2    ; Немаскируемое прерывание (NMI)
ISR_NO_ERROR   3    ; Точка останова (int3)
ISR_NO_ERROR   4    ; Переполнение (into)
ISR_NO_ERROR   5    ; Выход за границы (bound)
ISR_NO_ERROR   6    ; Неверная инструкция
ISR_NO_ERROR   7    ; Нет сопроцессора
ISR_WITH_ERROR 8    ; Двойная ошибка
ISR_NO_ERROR   9    ; (устарело)
ISR_WITH_ERROR 10   ; Неверный TSS
ISR_WITH_ERROR 11   ; Сегмент отсутствует
ISR_WITH_ERROR 12   ; Ошибка стека
ISR_WITH_ERROR 13   ; Общая ошибка защиты (General Protection Fault)
ISR_WITH_ERROR 14   ; Ошибка страницы (Page Fault)
ISR_NO_ERROR   15
ISR_NO_ERROR   16   ; Ошибка FPU
ISR_WITH_ERROR 17   ; Ошибка выравнивания
ISR_NO_ERROR   18   ; Machine Check
ISR_NO_ERROR   19   ; Ошибка SIMD
ISR_NO_ERROR   20
ISR_NO_ERROR   21
ISR_NO_ERROR   22
ISR_NO_ERROR   23
ISR_NO_ERROR   24
ISR_NO_ERROR   25
ISR_NO_ERROR   26
ISR_NO_ERROR   27
ISR_NO_ERROR   28
ISR_NO_ERROR   29
ISR_NO_ERROR   30
ISR_NO_ERROR   31

; ---- Аппаратные прерывания (IRQ 0..15 -> векторы 32..47) ----
IRQ 0               ; Системный таймер (PIT)
IRQ 1               ; Клавиатура
IRQ 2               ; Каскад (связь со вторым контроллером)
IRQ 3               ; COM2
IRQ 4               ; COM1
IRQ 5
IRQ 6               ; Дисковод
IRQ 7               ; LPT1
IRQ 8               ; Часы реального времени (RTC)
IRQ 9
IRQ 10
IRQ 11
IRQ 12              ; Мышь PS/2
IRQ 13              ; FPU
IRQ 14              ; Жёсткий диск (первичный канал)
IRQ 15              ; Жёсткий диск (вторичный канал)

; -----------------------------------------------------------------------------
;  Общая часть всех обработчиков.
;  После неё стек выглядит так (сверху вниз, от младших адресов к старшим):
;
;     ESP ->  gs, fs, es, ds                   <- push ds/es/fs/gs
;             edi, esi, ebp, esp, ebx, edx, ecx, eax   <- pusha
;             номер прерывания, код ошибки     <- заглушка
;             eip, cs, eflags                  <- процессор
;
;  Это в точности struct regs из interrupts.h! Указатель на неё (ESP)
;  передаём в C-функцию.
;
;  ВАЖНЫЙ ТРЮК (основа многозадачности): interrupt_handler ВОЗВРАЩАЕТ
;  указатель на структуру регистров, которую нужно восстановить. Обычно это
;  тот же указатель. Но планировщик может вернуть сохранённый стек ДРУГОЙ
;  задачи — тогда мы восстановим её регистры, и IRET вернёт нас уже в
;  другую задачу. Это и есть переключение контекста!
; -----------------------------------------------------------------------------
isr_common:
    pusha                       ; Сохранить EAX, ECX, EDX, EBX, ESP, EBP, ESI, EDI
    push ds                     ; Сохранить сегментные регистры
    push es
    push fs
    push gs

    mov  ax, 0x10               ; Загрузить сегмент данных ядра
    mov  ds, ax
    mov  es, ax
    mov  fs, ax
    mov  gs, ax

    push esp                    ; Аргумент: указатель на struct regs
    call interrupt_handler      ; EAX = указатель на regs для возврата
    mov  esp, eax               ; Переключаем стек (возможно, на другую задачу!)

    pop  gs                     ; Восстанавливаем всё в обратном порядке
    pop  fs
    pop  es
    pop  ds
    popa
    add  esp, 8                 ; Убрать номер прерывания и код ошибки
    iret                        ; Вернуться в прерванный код

; Служебная секция: сообщает компоновщику, что стек не должен быть исполняемым
section .note.GNU-stack noalloc noexec nowrite progbits
