; =============================================================================
;  entry.asm — ТОЧКА ВХОДА В ЯДРО
; =============================================================================
;  Загрузчик прыгает на адрес 0x10000. Компоновщик (см. linker.ld) кладёт
;  секцию .text.entry самой первой, поэтому по адресу 0x10000 окажется
;  именно метка _start.
;
;  Почему нельзя сразу прыгнуть в функцию на C?
;  Код на C рассчитывает, что:
;    - есть рабочий стек (его уже настроил загрузчик, но мы ставим заново);
;    - неинициализированные глобальные переменные (секция .bss) равны нулю.
;  Секция .bss не хранится в файле ядра (зачем хранить нули?), поэтому
;  обнулить её должны мы сами.
; =============================================================================
[bits 32]

section .text.entry
global _start
extern kmain                    ; Главная функция ядра (kernel.c)
extern __bss_start              ; Эти символы создаёт компоновщик (linker.ld)
extern __bss_end

_start:
    mov  esp, 0x90000           ; Стек ядра

    ; --- Обнуляем .bss: memset(__bss_start, 0, __bss_end - __bss_start) ---
    mov  edi, __bss_start       ; EDI = куда писать
    mov  ecx, __bss_end
    sub  ecx, edi               ; ECX = сколько байт
    xor  eax, eax               ; AL = 0 — что писать
    cld                         ; Направление: вперёд
    rep  stosb                  ; Повторить ECX раз: [EDI] = AL, EDI++

    call kmain                  ; Переходим в C!

    ; kmain никогда не должна возвращаться, но на всякий случай:
.hang:
    cli
    hlt
    jmp  .hang

; Служебная секция: сообщает компоновщику, что стек не должен быть исполняемым
section .note.GNU-stack noalloc noexec nowrite progbits
