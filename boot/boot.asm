; =============================================================================
;  boot.asm — ЗАГРУЗЧИК (bootloader) операционной системы MiniOS
; =============================================================================
;
;  Что это такое?
;  ---------------
;  Когда компьютер включается, процессор ничего не знает об операционной
;  системе. Первой запускается прошивка материнской платы — BIOS. Она проверяет
;  оборудование, а затем читает ПЕРВЫЙ СЕКТОР диска (512 байт) в память
;  по адресу 0x7C00 и передаёт туда управление.
;
;  Этот первый сектор называется MBR (Master Boot Record), а программа в нём —
;  загрузчиком. 512 байт — это очень мало, поэтому задача загрузчика простая:
;
;    1. Подготовить регистры и стек.
;    2. Прочитать с диска ядро ОС (оно лежит сразу за загрузчиком).
;    3. Включить линию A20 (чтобы была доступна память выше 1 МБ).
;    4. Загрузить таблицу GDT (описание сегментов памяти).
;    5. Перевести процессор из 16-битного "реального режима"
;       в 32-битный "защищённый режим".
;    6. Прыгнуть в ядро.
;
;  Подробное объяснение: docs/02-zagruzchik.md и docs/03-zashchishchennyj-rezhim.md
;
;  Ассемблер: NASM. Сборка: nasm -f bin boot.asm -o boot.bin -DKERNEL_SECTORS=N
; =============================================================================

[org 0x7C00]            ; BIOS кладёт нас по адресу 0x7C00 — сообщаем это NASM,
                        ; чтобы он правильно считал адреса меток.
[bits 16]               ; Процессор стартует в 16-битном реальном режиме.

KERNEL_SEGMENT  equ 0x1000      ; Ядро грузим в 0x1000:0x0000 = физ. адрес 0x10000
KERNEL_ADDRESS  equ 0x10000     ; (сегмент * 16 + смещение = 0x1000*16 + 0 = 0x10000)

%ifndef KERNEL_SECTORS
  %define KERNEL_SECTORS 64     ; Сколько секторов занимает ядро (Makefile
%endif                          ; подставляет точное число через -D)

; -----------------------------------------------------------------------------
;  Точка входа. Сюда BIOS передаёт управление.
;  В регистре DL BIOS оставляет номер диска, с которого мы загрузились.
; -----------------------------------------------------------------------------
start:
    cli                         ; Запрещаем прерывания, пока настраиваем стек
    xor  ax, ax                 ; AX = 0
    mov  ds, ax                 ; Все сегментные регистры = 0, т.к. мы
    mov  es, ax                 ; используем [org 0x7C00] и абсолютные адреса
    mov  ss, ax
    mov  sp, 0x7C00             ; Стек растёт ВНИЗ от 0x7C00 (под загрузчиком)
    sti                         ; Снова разрешаем прерывания (BIOS они нужны)

    mov  [boot_drive], dl       ; Запоминаем номер загрузочного диска

    mov  ax, 0x0003             ; Функция BIOS 0x00: установить видеорежим 3
    int  0x10                   ; (текст 80x25, 16 цветов) — заодно очищает экран

    mov  si, msg_boot
    call print_string

; -----------------------------------------------------------------------------
;  ШАГ 1. Чтение ядра с диска.
;  Используем расширенную функцию BIOS int 0x13, AH=0x42 (чтение по LBA).
;  LBA (Logical Block Addressing) — сектора нумеруются просто 0, 1, 2, ...
;  Сектор 0 — это мы (загрузчик), ядро начинается с сектора 1.
;  Читаем по одному сектору в цикле: это медленнее, но проще и надёжнее.
; -----------------------------------------------------------------------------
    mov  cx, KERNEL_SECTORS     ; CX — счётчик цикла (сколько секторов осталось)
.read_loop:
    mov  si, disk_packet        ; DS:SI -> структура-запрос (Disk Address Packet)
    mov  ah, 0x42               ; Функция "расширенное чтение"
    mov  dl, [boot_drive]       ; С какого диска читать
    int  0x13                   ; Вызов BIOS
    jc   disk_error             ; Флаг CF=1 означает ошибку

    add  word [dap_segment], 0x20   ; Следующий сектор кладём на 512 байт дальше
                                    ; (0x20 параграфов * 16 = 512 байт)
    add  dword [dap_lba], 1         ; Следующий номер сектора на диске
    loop .read_loop                 ; CX = CX - 1; если CX != 0 — повторить

    mov  si, msg_loaded
    call print_string

; -----------------------------------------------------------------------------
;  ШАГ 2. Включение линии A20.
;  Исторически (ради совместимости с процессором 8086) 21-я адресная линия
;  была отключена, и адреса выше 1 МБ "заворачивались" на начало памяти.
;  Чтобы использовать всю память, A20 нужно включить.
;  Сначала просим BIOS (int 0x15, AX=0x2401), затем на всякий случай
;  используем "быстрый" способ через системный порт 0x92.
; -----------------------------------------------------------------------------
    mov  ax, 0x2401
    int  0x15
    in   al, 0x92
    or   al, 00000010b          ; Бит 1 порта 0x92 = включить A20
    and  al, 11111110b          ; Бит 0 НЕ трогаем (он перезагружает машину!)
    out  0x92, al

; -----------------------------------------------------------------------------
;  ШАГ 3. Переход в защищённый режим.
;    a) запрещаем прерывания (таблицы прерываний BIOS в 32-битном режиме
;       не работают, а свою мы настроим позже, уже в ядре);
;    b) загружаем GDT командой LGDT;
;    c) устанавливаем бит PE (Protection Enable) в регистре CR0;
;    d) делаем "дальний прыжок" — он загружает в CS селектор 32-битного
;       сегмента кода и очищает конвейер процессора.
; -----------------------------------------------------------------------------
    cli
    lgdt [gdt_descriptor]
    mov  eax, cr0
    or   eax, 1                 ; Бит 0 регистра CR0 = PE
    mov  cr0, eax
    jmp  CODE_SEG:protected_mode_start

; -----------------------------------------------------------------------------
;  Вспомогательные 16-битные процедуры
; -----------------------------------------------------------------------------

; print_string: печатает строку, заканчивающуюся нулём. Адрес строки — в SI.
; Использует функцию BIOS int 0x10, AH=0x0E ("телетайп": вывести символ).
print_string:
    pusha
    mov  ah, 0x0E
.next_char:
    lodsb                       ; AL = [SI], SI = SI + 1
    test al, al                 ; Конец строки (байт 0)?
    jz   .done
    int  0x10
    jmp  .next_char
.done:
    popa
    ret

disk_error:
    mov  si, msg_disk_error
    call print_string
.halt:
    cli
    hlt
    jmp  .halt

; -----------------------------------------------------------------------------
;  32-битный код. Сюда мы попадаем после дальнего прыжка.
; -----------------------------------------------------------------------------
[bits 32]
protected_mode_start:
    mov  ax, DATA_SEG           ; Во все сегментные регистры данных
    mov  ds, ax                 ; загружаем селектор сегмента данных из GDT
    mov  es, ax
    mov  fs, ax
    mov  gs, ax
    mov  ss, ax
    mov  esp, 0x90000           ; Новый стек ядра (растёт вниз от 0x90000)

    jmp  KERNEL_ADDRESS         ; ПРЫЖОК В ЯДРО! Загрузчик больше не нужен.

; =============================================================================
;  ДАННЫЕ
; =============================================================================

; Disk Address Packet — структура для функции int 0x13 AH=0x42
disk_packet:
    db 0x10                     ; Размер структуры (16 байт)
    db 0                        ; Зарезервировано
    dw 1                        ; Сколько секторов читать за один вызов
    dw 0x0000                   ; Смещение буфера
dap_segment:
    dw KERNEL_SEGMENT           ; Сегмент буфера (куда класть данные)
dap_lba:
    dq 1                        ; Номер сектора на диске (начинаем с 1)

boot_drive: db 0

msg_boot:       db "MiniOS bootloader: loading kernel", 0
msg_loaded:     db " OK", 13, 10, "Switching to protected mode...", 0
msg_disk_error: db " DISK ERROR!", 0

; -----------------------------------------------------------------------------
;  GDT — Global Descriptor Table (глобальная таблица дескрипторов)
;  Каждый дескриптор (8 байт) описывает сегмент: базу, предел, права.
;  Мы используем "плоскую" модель памяти: и код, и данные начинаются с 0
;  и имеют размер 4 ГБ, то есть сегментация фактически отключена.
; -----------------------------------------------------------------------------
gdt_start:
gdt_null:                       ; Дескриптор 0 обязан быть нулевым
    dq 0

gdt_code:                       ; Дескриптор 1 — сегмент КОДА (селектор 0x08)
    dw 0xFFFF                   ; Предел, биты 0-15
    dw 0x0000                   ; База, биты 0-15
    db 0x00                     ; База, биты 16-23
    db 10011010b                ; Права: присутствует, кольцо 0, код, чтение
    db 11001111b                ; Флаги: гранулярность 4 КБ, 32 бита + предел 16-19
    db 0x00                     ; База, биты 24-31

gdt_data:                       ; Дескриптор 2 — сегмент ДАННЫХ (селектор 0x10)
    dw 0xFFFF
    dw 0x0000
    db 0x00
    db 10010010b                ; Права: присутствует, кольцо 0, данные, запись
    db 11001111b
    db 0x00
gdt_end:

gdt_descriptor:                 ; Структура для команды LGDT:
    dw gdt_end - gdt_start - 1  ;   размер таблицы минус 1
    dd gdt_start                ;   линейный адрес таблицы

CODE_SEG equ gdt_code - gdt_start   ; = 0x08
DATA_SEG equ gdt_data - gdt_start   ; = 0x10

; -----------------------------------------------------------------------------
;  Подпись загрузочного сектора.
;  Сектор должен занимать ровно 512 байт, а последние 2 байта должны быть
;  0x55 0xAA — иначе BIOS не посчитает диск загрузочным.
; -----------------------------------------------------------------------------
times 510 - ($ - $$) db 0
dw 0xAA55
